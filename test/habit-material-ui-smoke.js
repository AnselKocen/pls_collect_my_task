const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), net = require('node:net');
const { spawn } = require('node:child_process'), { once } = require('node:events');
const AdmZip = require('adm-zip');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'memo-material-ui-'));
fs.mkdirSync(path.join(root, 'profile'));app.setPath('userData', path.join(root, 'profile'));app.disableHardwareAcceleration();
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
let child, window, logs = '';
const read = expression => window.webContents.executeJavaScript(expression);
async function until(expression) {
  for (let i = 0; i < 400; i++) { if (await read(expression)) return;await delay(25); }
  throw new Error('UI wait failed: ' + expression);
}
async function run() {
  const dataDir = path.join(root, 'data');fs.mkdirSync(dataDir);
  const seed = require('../storage/defaults')();seed['settings.json'].agent = 'cc';seed['habit_pools.json'].pools = [];
  for (const [file, value] of Object.entries(seed)) fs.writeFileSync(path.join(dataDir, file), JSON.stringify(value));
  const node = process.env.MEMO_TEST_NODE || process.execPath, fake = path.join(root, 'fake-claude');
  const quote = value => "'" + value.replace(/'/g, "'\\''") + "'";
  fs.writeFileSync(fake, `#!/bin/sh\nexec ${quote(node)} ${quote(path.join(__dirname, 'fake-model-cli.js'))} "$@"\n`, { mode: 0o755 });
  const mode = path.join(root, 'mode'), capture = path.join(root, 'calls.jsonl');fs.writeFileSync(mode, 'slow');
  const probe = net.createServer();probe.listen(0, '127.0.0.1');await once(probe, 'listening');
  const port = probe.address().port;await new Promise(resolve => probe.close(resolve));
  child = spawn(node, [path.join(__dirname, '../server.js')], { env: { ...process.env, ELECTRON_RUN_AS_NODE: '1', MEMO_ELECTRON: '1', MEMO_CONFIG_DIR: root, MEMO_DATA_DIR: dataDir, PORT: String(port), CLAUDE_CLI: fake, MEMO_FAKE_CC_INVALID_FILE: mode, MEMO_FAKE_CC_CAPTURE: capture }, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stderr.on('data', chunk => { logs += chunk; });
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(logs)), 12000);
    child.stdout.on('data', chunk => { logs += chunk;if (logs.includes('Memo server running')) { clearTimeout(timer);resolve(); } });
    child.once('exit', code => { clearTimeout(timer);reject(new Error('Startup ' + code + ': ' + logs)); });
  });
  window = new BrowserWindow({ show: false, width: 1100, height: 900, webPreferences: { offscreen: true, contextIsolation: true, nodeIntegration: false, sandbox: true } });
  window.webContents.session.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (details, done) => done({ cancel: !details.url.startsWith(`http://127.0.0.1:${port}/`) }));
  await window.loadURL(`http://127.0.0.1:${port}/`);await until('agentStatusKnown && aiState.configured');
  await read(`document.getElementById('btnHabitTrack').click()`);
  const out = process.env.MEMO_UI_SCREENSHOT_DIR;
  const shot = async name => { if (out) { await delay(180);fs.mkdirSync(out, { recursive: true });fs.writeFileSync(path.join(out, name), (await window.webContents.capturePage()).toPNG()); } };
  async function fileInput(name, buffer, drop = false) {
    await read(`(()=>{const data=Uint8Array.from(atob(${JSON.stringify(buffer.toString('base64'))}),c=>c.charCodeAt(0));const transfer=new DataTransfer();transfer.items.add(new File([data],${JSON.stringify(name)}));${drop ? "const area=document.getElementById('habitUploadArea');area.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:transfer}));if(!area.classList.contains('dragover'))throw new Error('No drag feedback');area.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}));" : "const input=document.getElementById('habitFileInput');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));"}})()`);
  }
  const calls = () => fs.existsSync(capture) ? fs.readFileSync(capture, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : [];
  const fillText = async text => read(`document.getElementById('habitMaterialText').value=${JSON.stringify(text)};document.getElementById('habitMaterialText').dispatchEvent(new Event('input',{bubbles:true}))`);
  const submit = () => read(`document.getElementById('habitMaterialSubmit').click()`);
  assert.equal(await read(`document.getElementById('habitUploadArea').contains(document.getElementById('habitMaterialText')) && document.getElementById('habitUploadArea').contains(document.getElementById('habitMaterialPick')) && document.getElementById('habitUploadArea').contains(document.getElementById('habitMaterialSubmit'))`), true, 'Text, upload and generate should share one input frame');
  assert.equal(await read(`document.getElementById('habitTextEntry')===null`), true, 'Old separate text entry should be gone');
  assert.equal(await read(`document.getElementById('habitMaterialSubmit').disabled`), true);
  await shot('material-unified-desktop.png');
  const draft = '我输入的文字草稿，要在选择文件后保留。';
  await fillText(draft);
  await read(`(()=>{let picked=false;document.getElementById('habitFileInput').addEventListener('click',event=>{event.preventDefault();picked=true},{once:true});document.getElementById('habitMaterialPick').click();if(!picked)throw new Error('Upload button did not open file picker')})()`);
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), draft);
  await fileInput('unsupported.png', Buffer.from('image'));
  await until(`!document.getElementById('habitMaterialError').classList.contains('hidden')`);
  assert.equal(calls().length, 0, 'Unsupported files should not invoke AI');
  assert.match(await read(`document.getElementById('habitMaterialError').textContent`), /TXT/);
  await fileInput('练习笔记.TXT', Buffer.from('从窗边观察开始，每天散步五分钟、阅读一页、收拾桌面。'));
  await delay(150);
  assert.equal(calls().length, 0, 'Selecting a file must wait for explicit generation');
  assert.equal(await read('habitGenerating'), false);
  assert.equal(await read(`document.getElementById('habitMaterialFileName').textContent`), '练习笔记.TXT');
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), draft);
  assert.equal(await read(`document.getElementById('habitUseFile').getAttribute('aria-pressed')`), 'true');
  await shot('material-selected-file-desktop.png');
  await read(`document.getElementById('habitUseText').click()`);
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), draft);
  assert.equal(await read(`document.getElementById('habitMaterialFileName').textContent`), '练习笔记.TXT', 'Switching source should retain the file draft');
  await read(`document.getElementById('habitUseFile').click();document.getElementById('habitMaterialRemove').click()`);
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), draft);
  assert.equal(await read(`document.getElementById('habitMaterialFilePreview').classList.contains('hidden')`), true);
  await fileInput('更换的练习.txt', Buffer.from('将被明确更换的素材内容。'));
  await fileInput('练习笔记.TXT', Buffer.from('从窗边观察开始，每天散步五分钟、阅读一页、收拾桌面。'));
  assert.equal(calls().length, 0, 'Changing selected files must not invoke AI');
  await submit();
  await until('habitGenerating');
  await read(`document.getElementById('habitUploadArea').requestSubmit()`);
  assert.equal(await read(`document.getElementById('habitMaterialSubmit').disabled`), true);
  await read(`document.getElementById('tagSummaryClose').click();document.getElementById('btnHabitTrack').click()`);
  assert.equal(await read(`document.getElementById('habitUploadProgress').classList.contains('hidden')`), false, 'Reopening should restore progress');
  await shot('material-file-generating.png');
  await until('habitPools.length===1 && !habitGenerating');
  assert.equal(await read('habitPools[0].habits.length'), 30);
  assert.equal(await read('habitPools[0].sourceFile'), '练习笔记.TXT');
  assert.equal(await read(`document.getElementById('habitFileInput').value`), '');
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), draft, 'File generation must retain the separate text draft');
  fs.rmSync(mode);
  const zip = new AdmZip();zip.addFile('skills/笔记.txt', Buffer.from('每天观察窗外，写下三个发现。'));
  await fileInput('旧素材.zip', zip.toBuffer(), true);
  await delay(100);
  assert.equal(calls().length, 1, 'Dropping a file must also wait for explicit generation');
  await submit();
  await until('habitPools.length===2 && !habitGenerating');
  assert.equal(await read('habitPools[1].habits.length'), 30);
  await fileInput('损坏素材.pdf', Buffer.from('not a PDF'));
  await submit();
  await until(`!document.getElementById('habitMaterialError').classList.contains('hidden') && !habitGenerating`);
  assert.equal(await read('habitPools.length'), 2);
  assert.equal(await read(`document.getElementById('habitMaterialFileName').textContent`), '损坏素材.pdf', 'Failed generation should keep the selected file for retry or replacement');
  const callsBeforeText = calls().length;
  await read(`document.getElementById('habitMaterialRemove').click()`);
  await fillText('   ');
  await read(`document.getElementById('habitUploadArea').requestSubmit()`);
  await delay(100);
  assert.equal(calls().length, callsBeforeText);
  window.setSize(390, 820);await delay(120);
  const sample = '练习素材：每天读一页书，留意呼吸，整理桌面，记下今天的小发现。';
  await read(`document.getElementById('habitMaterialText').focus();window.habitWishDialog.close();if(document.activeElement.id!=='habitMaterialText')throw new Error('Repeated child close stole text-input focus')`);
  await fillText(sample);
  await read(`document.getElementById('habitUploadArea').scrollIntoView({block:'center'})`);
  await shot('material-unified-mobile.png');
  fs.writeFileSync(mode, 'habit-pool');
  await submit();
  await until(`!document.getElementById('habitMaterialError').classList.contains('hidden') && !habitGenerating`);
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), sample, 'Failed text generation must keep the input');
  assert.equal(await read(`document.getElementById('habitUploadArea').classList.contains('hidden')`), false);
  assert.equal(await read('habitPools.length'), 2);
  await shot('material-text-retry-mobile.png');
  fs.rmSync(mode);
  await fileInput('暂存文件.txt', Buffer.from('这一份文件只暂存，不应混进文字生成。'));
  await read(`document.getElementById('habitUseText').click()`);
  await submit();
  await until('habitPools.length===3 && !habitGenerating');
  assert.equal(await read('habitPools[2].habits.length'), 30);
  assert.equal(await read('habitPools[2].sourceFile'), '粘贴文字');
  assert.equal(await read(`document.getElementById('habitMaterialText').value`), '');
  assert.equal(await read(`document.getElementById('habitMaterialFileName').textContent`), '暂存文件.txt', 'Text generation must retain the separate file draft');
  assert.equal(await read(`document.getElementById('habitMaterialSubmit').disabled`), true, 'Retained file must not silently become the active source');
  await read(`document.getElementById('habitUseFile').click()`);
  assert.equal(await read(`document.getElementById('habitMaterialSubmit').disabled`), false);
  assert.equal(await read(`document.getElementById('habitMaterialError').classList.contains('hidden')`), true);
  assert.equal(await read(`(()=>{const panel=document.getElementById('habitPanelPools');return panel.scrollWidth<=panel.clientWidth+2})()`), true, 'Mobile material UI overflows');
  await shot('material-pools-mobile.png');
  const requests = calls();
  assert.equal(requests.filter(call => call.task === 'habit-pool').length, 4);
  assert.equal(requests.at(-1).input.book.includes(sample), true, 'Pasted text did not reach generation');
  assert.equal(requests.at(-1).input.book.includes('这一份文件只暂存'), false, 'Both sources were submitted together');
  console.log(JSON.stringify({ unifiedInput: true, selectionWaitsForGenerate: true, changingAndRemovingFiles: true, draftsPreservedAcrossSourceSwitch: true, oneSourcePerGeneration: true, selectedTxt: true, droppedZip: true, textGeneration: true, parserErrorVisible: true, duplicateSubmissionGuard: true, failedFileAndTextRetained: true, retry: true, reopenWhileGenerating: true, mobileLayout: true, savedPools: 3, model: 'simulated' }));
}
app.whenReady().then(run).catch(error => { console.error(error.stack);console.error(logs);process.exitCode = 1; }).finally(async () => {
  window?.destroy();if (child && child.exitCode === null && child.signalCode === null) { child.kill('SIGTERM');await once(child, 'close'); }
  fs.rmSync(root, { recursive: true, force: true });app.exit(process.exitCode || 0);
});
